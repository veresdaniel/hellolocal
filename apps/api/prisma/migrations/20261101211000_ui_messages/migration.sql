-- Landing copy edited in the admin was stored inside Brand.planOverrides.
-- Fold those strings into the same table so they stay the published text.
CREATE OR REPLACE FUNCTION pg_temp.flatten_ui_copy(prefix text, obj jsonb, lang text) RETURNS void AS $$
DECLARE
  entry record;
BEGIN
  FOR entry IN SELECT * FROM jsonb_each(obj) LOOP
    IF jsonb_typeof(entry.value) = 'string' AND btrim(entry.value #>> '{}') <> '' THEN
      INSERT INTO "UiMessage" ("lang", "key", "value")
      VALUES (lang, prefix || entry.key, entry.value #>> '{}')
      ON CONFLICT ("lang", "key") DO UPDATE SET "value" = EXCLUDED."value";
    ELSIF jsonb_typeof(entry.value) = 'object' THEN
      PERFORM pg_temp.flatten_ui_copy(prefix || entry.key || '.', entry.value, lang);
    END IF;
  END LOOP;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE
  overrides jsonb;
  lang text;
  copy jsonb;
BEGIN
  SELECT "planOverrides" INTO overrides FROM "Brand" ORDER BY "createdAt" ASC LIMIT 1;
  IF overrides IS NULL OR jsonb_typeof(overrides->'landingCopy') <> 'object' THEN
    RETURN;
  END IF;
  FOR lang, copy IN SELECT * FROM jsonb_each(overrides->'landingCopy') LOOP
    IF lang ~ '^[a-z]{2,3}$' AND jsonb_typeof(copy) = 'object' THEN
      INSERT INTO "UiLanguage" ("code", "sortOrder") VALUES (lang, 100)
      ON CONFLICT ("code") DO NOTHING;
      PERFORM pg_temp.flatten_ui_copy('public.overview.', copy, lang);
    END IF;
  END LOOP;
END $$;
