-- Public interface languages and their strings.
-- Existing hu/en/de catalogs are copied out of the JSON files.
-- A later block copies any landing-copy overrides already stored on Brand.

CREATE TABLE "UiLanguage" (
  "code" VARCHAR(8) NOT NULL,
  "sortOrder" INTEGER NOT NULL DEFAULT 0,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "UiLanguage_pkey" PRIMARY KEY ("code")
);

CREATE TABLE "UiMessage" (
  "lang" VARCHAR(8) NOT NULL,
  "key" VARCHAR(180) NOT NULL,
  "value" TEXT NOT NULL,
  CONSTRAINT "UiMessage_pkey" PRIMARY KEY ("lang", "key")
);

CREATE INDEX "UiMessage_key_idx" ON "UiMessage"("key");

ALTER TABLE "UiMessage"
  ADD CONSTRAINT "UiMessage_lang_fkey"
  FOREIGN KEY ("lang") REFERENCES "UiLanguage"("code") ON DELETE CASCADE ON UPDATE CASCADE;

